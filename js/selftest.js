    const changed = Store.setRounding('insulin', 'ceil');
    assert('rounding: switching to up reflows existing lines', changed === 1 && Store.state.lines.get(apidra.id).packs === 4);
    Store.add(concor.id, 31);
    assert('rounding: per-engine — pack items stay nearest', Store.state.lines.get(concor.id).packs === 1);
    Store.edit(apidra.id, 'pack', 9);
    Store.setRounding('insulin', 'floor');
    assert('rounding: manual packs survive a rule change', Store.state.lines.get(apidra.id).packs === 9);
    Store.resetPacks(apidra.id);
    assert('rounding: floor after reset → 3', Store.state.lines.get(apidra.id).packs === 3);
    Store.setMinOne(false);
    Store.edit(concor.id, 'req', 10);
    assert('rounding: min-one off allows 0 packs', Store.state.lines.get(concor.id).packs === 0);
    Store.setMinOne(true);
    assert('rounding: min-one on lifts back to 1', Store.state.lines.get(concor.id).packs === 1);
    Store.state.prefs.rounding = {}; Store.state.prefs.minOne = true;

    reset();
    App.db.filter(d => !d.isDynamic).slice(0, 5).forEach(d => Store.add(d.id, 10));
    assert('undo: 5 adds → 5 lines', Store.state.lines.size === 5 && Store.undoStack.length === 5);
    for (let i = 0; i < 5; i++) Store.undo();
    assert('undo: 5 undos → empty, 0.00 total', Store.state.lines.size === 0 && money(Store.totalP()) === '0.00');
    Store.add(concor.id, 30); Store.remove(concor.id); Store.undo();
    assert('undo: removal restores the line', Store.state.lines.get(concor.id).req === 30);
    Store.clear(); Store.undo();
    assert('undo: clear is reversible', Store.state.lines.has(concor.id));
    const before = Store.undoStack.length;
    Store.edit(concor.id, 'req', 31); Store.edit(concor.id, 'req', 32); Store.edit(concor.id, 'req', 33);
    assert('undo: rapid edits to one field coalesce', Store.undoStack.length === before + 1);

    reset();
    const c1 = Store.activeCalc();
    Store.add(concor.id, 30);
    const c2 = Store.newCalc('Patient B').calc;
    assert('calcs: new calculation becomes active', Store.state.active === c2.id && Store.state.calcs.length === 2);
    assert('calcs: new calc gets a distinct color', c1.hue !== c2.hue);
    Store.add(concor.id, 60);
    assert('calcs: lines are independent per calc', c1.lines.get(concor.id).req === 30 && c2.lines.get(concor.id).req === 60);
    Store.add(apidra.id, 300, 0, true, c1.id);
    assert('calcs: add can target a non-active calc', c1.lines.has(apidra.id) && !c2.lines.has(apidra.id) && Store.state.active === c2.id);
    const mem = Store.membership(concor.id);
    assert('calcs: membership lists every calc holding an item', mem.length === 2 && mem.find(m => m.active).calc === c2 && mem[0].pos === 1);
    Store.switchTo(c1.id);
    assert('calcs: switching keeps both calcs intact', Store.state.active === c1.id && Store.state.lines.size === 2 && c2.lines.size === 1);
    const t1 = Store.transferLine(apidra.id, c1.id, c2.id, 'move');
    assert('calcs: move transfers a line', t1.ok && !c1.lines.has(apidra.id) && c2.lines.get(apidra.id).req === 300);
    const t2 = Store.transferLine(concor.id, c1.id, c2.id, 'copy');
    assert('calcs: copy combines with existing line', t2.ok && t2.merged && c1.lines.has(concor.id) && c2.lines.get(concor.id).req === 90 && c2.lines.get(concor.id).packs === 3);
    Store.undo();
    assert('calcs: transfer is undoable', Store.calc(c2.id).lines.get(concor.id).req === 60 && Store.calc(c1.id).lines.has(concor.id));
    const t3 = Store.transferLine(concor.id, c1.id, '__new', 'copy');
    assert('calcs: transfer to a new calculation', t3.ok && Store.state.calcs.length === 3 && t3.to.lines.get(concor.id).req === 30);
    Store.undo();
    const d1 = Store.duplicateCalc(Store.state.calcs[1].id);
    assert('calcs: duplicate inserts after source', d1.ok && Store.state.calcs[2].id === d1.calc.id && d1.calc.lines.size === Store.state.calcs[1].lines.size);
    Store.moveCalc(d1.calc.id, 0);
    assert('calcs: reorder moves a calc', Store.state.calcs[0].id === d1.calc.id && Store.byPosition(1).id === d1.calc.id);
    Store.undo();
    const m1 = Store.mergeCalc(d1.calc.id, Store.state.calcs[1].id);
    const tgt = Store.state.calcs[1];
    assert('calcs: merge folds lines & removes source', m1.ok && Store.state.calcs.length === 2 && tgt.lines.get(concor.id).req === 120 && !Store.calc(d1.calc.id));
    Store.undo();
    assert('calcs: merge is undoable', Store.state.calcs.length === 3);
    const grand = Store.state.calcs.reduce((a, c) => a + Store.totalP(c.lines), 0);
    assert('calcs: grand total sums every calc', Store.grandTotalP() === grand && grand > 0);
    const name = Store.deleteCalc(Store.state.calcs[0].id);
    assert('calcs: delete removes and picks a neighbour', name && Store.state.calcs.length === 2 && Store.calc(Store.state.active));
    Store.undo();
    assert('calcs: delete is undoable', Store.state.calcs.length === 3);
    assert('calcs: rename', Store.renameCalc(Store.state.calcs[0].id, 'Ward 3') && Store.state.calcs[0].name === 'Ward 3');
    assert('calcs: switchBy wraps around', (Store.switchTo(Store.state.calcs[2].id), Store.switchBy(1).ok) && Store.state.active === Store.state.calcs[0].id);
    Store.deleteCalc(Store.state.calcs[0].id); Store.deleteCalc(Store.state.calcs[0].id); Store.deleteCalc(Store.state.calcs[0].id);
    assert('calcs: deleting the last one leaves a fresh empty calc', Store.state.calcs.length === 1 && Store.state.lines.size === 0);

    reset();
    const ws = Store.serializeWorkspace();
    assert('persist: workspace serialises calcs', Array.isArray(ws.calcs) && ws.calcs.length === 1 && ws.v === SCHEMA_VERSION);
    const legacy = [['old-random-id', { req: 5, packs: 1, cost: 10, supplyPrice: 0, item: { n: 'Toujeo', t: 'قوي عاملة', u: 'Pen', s: 'Unified Purchase' } }], ['x', { item: { n: 'nope' } }], ['bad']];
    const hyd = Store.hydrateEntries(legacy);
    assert('migration: v4.5 entry remaps to current id', hyd.length === 1 && hyd[0][0] === toujeo.id);
    const hyd2 = Store.hydrateEntries([[apidra.id, { req: 1020, packs: 4 }]], true);
    assert('migration: legacy ceil packs become automatic', !hyd2[0][1].manual && hyd2[0][1].packs === 3);
    const hyd3 = Store.hydrateEntries([[apidra.id, { req: 1020, packs: 7 }]], true);
    assert('migration: legacy hand-edited packs stay manual', hyd3[0][1].manual && hyd3[0][1].packs === 7);
    localStorage.removeItem(KEYS.ws);
    localStorage.setItem(KEYS.orders, JSON.stringify([{ id: '1', name: 'Old A', items: [[concor.id, { req: 30, packs: 1 }]] }, { id: '2', name: 'Old B', items: [[apidra.id, { req: 600, packs: 2 }]] }]));
    localStorage.setItem(KEYS.calc, JSON.stringify([[concor.id, { req: 60, packs: 2 }]]));
    localStorage.setItem(KEYS.cur, '0');
    const lr = Store.load();
    assert('migration: v5 orders become calculations', lr.migrated && Store.state.calcs.length === 2 && Store.state.calcs[0].name === 'Old A' && Store.activeCalc().name === 'Old A' && Store.state.lines.get(concor.id).req === 60);
    localStorage.removeItem(KEYS.ws);
    localStorage.setItem(KEYS.orders, '[]');
    localStorage.setItem(KEYS.calc, JSON.stringify([[concor.id, { req: 30, packs: 1 }]]));
    localStorage.setItem(KEYS.cur, '-1');
    Store.load();
    assert('migration: unsaved draft is kept as a calculation', Store.state.calcs.length === 1 && Store.state.lines.size === 1);
    reset();
    const imp = Store.importEntries({ title: 'Legacy', items: legacy });
    assert('import: v5 file drops unknown, keeps valid, replaces empty calc', imp.ok && imp.count === 1 && imp.dropped === 2 && Store.state.calcs.length === 1 && Store.activeCalc().name === 'Legacy');
    const imp2 = Store.importEntries({ calcs: [{ name: 'X', items: [[concor.id, { req: 30, packs: 1, manual: false }]] }, { name: 'Y', items: [] }] });
    assert('import: 5.5 multi-calc file adds calculations', imp2.ok && imp2.calcs === 2 && Store.state.calcs.length === 3);

    reset();
    Store.state.prefs.addMode = 'unit';
    els.in.value = ''; App.armed = false; search();
    assert('omni: empty is IDLE', App.omniState === 'IDLE');
    els.in.value = 'concor'; App.armed = false; search();
    assert('omni: text is SEARCHING', App.omniState === 'SEARCHING');
    els.in.value = 'concor 5 x30'; App.armed = false; search();
    assert('omni: qty is ARMED_WITH_QTY', App.omniState === 'ARMED_WITH_QTY');
    assert('omni: target chip hidden with one calc', els.target.hidden);
    els.in.value = `${dyn.n} x2`; App.armed = false; search();
    assert('omni: share item without price NEEDS_PRICE', App.omniState === 'ARMED_NEEDS_PRICE');
    els.in.value = `${dyn.n} @450 x2`; App.armed = false; search();
    assert('omni: @price skips NEEDS_PRICE', App.omniState === 'ARMED_WITH_QTY');
    els.in.value = 'concor'; App.armed = false; search();
    press(els.in, 'Tab');
    assert('omni: Tab completes & arms', App.armed && App.omniState === 'ARMED_PENDING_QTY');
    els.in.value = 'concor 5 x30'; App.armed = false; search();
