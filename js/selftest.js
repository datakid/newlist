    press(els.in, 'Enter');
    assert('loop: Enter commits and returns to IDLE', Store.state.lines.get(concor.id).req === 30 && App.omniState === 'IDLE' && document.activeElement === els.in);
    els.in.value = 'concor 5 x5'; App.armed = false; search();
