    assert('loop: insulin IU → pens (900u → 2)', tj && tj.packs === 2);
    els.in.value = 'concor 5 x2p'; App.armed = false; search();
    press(els.in, 'Enter');
    assert('loop: x2p adds packs', Store.state.lines.get(concor.id).req === 100);
    els.in.value = `${dyn.n} x2`; App.armed = false; search();
    press(els.in, 'Enter');
    assert('price: Enter reveals price field', !els.priceWrap.hidden && document.activeElement === els.price);
    els.price.value = '450';
    press(els.price, 'Enter');
    assert('price: Enter in price commits', Store.state.lines.has(dyn.id) && App.omniState === 'IDLE');

    const first = Store.activeCalc();
    const second = Store.newCalc().calc;
    Store.switchTo(first.id);
    els.in.value = 'concor 5 x30'; App.armed = false; search();
    assert('omni: target chip shows with several calcs', !els.target.hidden && els.target.textContent.includes(first.name));
    els.in.value = 'concor 5 x30 #2'; App.armed = false; search();
    assert('omni: #2 overrides the target chip', els.target.classList.contains('override') && els.target.textContent.includes(second.name));
    press(els.in, 'Enter');
    assert('loop: #2 adds to calc 2 without switching', second.lines.get(concor.id).req === 30 && Store.state.active === first.id);
    els.in.value = 'concor 5 x30 #9'; App.armed = false; search();
    assert('omni: unknown #n is flagged', els.target.classList.contains('bad') && els.hint.classList.contains('err'));
    press(els.in, 'Enter');
    assert('loop: unknown #n does not add', Store.state.lines.get(concor.id).req === 100);
    els.in.value = 'concor 5'; App.armed = false; search();
    const row = rowCache.get(concor.id);
    assert('row: shows badge for the other calc', row && row.querySelector(`.mb .num[data-cid="${second.id}"]`));
    row.querySelector(`.mb .num[data-cid="${second.id}"]`).click();
