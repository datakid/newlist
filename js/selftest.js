    assert('loop: Shift+Enter keeps query', els.in.value === 'concor 5 x5' && Store.state.lines.get(concor.id).req === 35);
    press(els.in, 'Enter');
    assert('loop: repeat Enter adds again', Store.state.lines.get(concor.id).req === 40);
